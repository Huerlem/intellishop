import { v4 as uuidv4 } from 'uuid';

/**
* This file contains the Firestore database structure for the app
* It serves as a reference for the data types and collection structure
*/

/**
* Collection: users
* Description: Stores information about users
*
* Fields:
* - uid: string (user ID in Firebase Auth)
* - email: string
* - displayName: string
* - phoneNumber: string
* - address: {
* street: string,
* city: string,
* postcode: string,
* country: string (default: "UK")
* }
* - photoURL: string (profile image URL)
* - createdAt: timestamp
* - updatedAt: timestamp
* - lastLogin: timestamp
* - role: string (user, admin)
* - isActive: boolean
* - settings: {
* notifications: boolean,
* theme: string,
* language: string
* } */

/**
* Collection: shoppingLists
* Description: Stores users' shopping lists
*
* Fields:
* - id: string (automatically generated)
* - userId: string (reference to the user)
* - name: string (list name)
* - createdAt: timestamp
* - updatedAt: timestamp
* - isActive: boolean
* - isAIGenerated: boolean (indicates whether it was generated by AI)
* - totalBudget: number (total budget for this list, optional)
* - items: array of {
* id: string,
* name: string,
* quantity: number,
* unit: string (un, kg, l, etc),
* estimatedPrice: number (optional),
* checked: boolean,
* addedToStock: boolean,
* category: string (optional),
* notes: string (optional),
* }
*/

/**
* Collection: stockItems
* Description: Stores items from the user's stock
*
* Fields:
* - id: string (automatically generated)
* - userId: string (user reference)
* - name: string (product name)
* - category: string (product category)
* - quantity: number (current quantity)
* - unit: string (unit of measurement)
* - minQuantity: number (minimum desired quantity)
* - expiryDate: timestamp (optional)
* - lastPurchaseDate: timestamp (optional)
* - lastPurchasePrice: number (optional)
* - createdAt: timestamp
* - updatedAt: timestamp
* - image: string (product image URL, optional)
* - barcode: string (barcode, optional)
* - notes: string (additional notes, optional)
*/

/**
* Collection: aiSuggestions
* Description: Stores suggestions AI-generated shopping list
*
* Fields:
* - id: string (automatically generated)
* - userId: string (reference to the user)
* - createdAt: timestamp
* - budget: number (budget entered by the user)
* - items: array of {
* name: string,
* quantity: number,
* unit: string,
* estimatedPrice: number,
* category: string (optional)
* }
* - totalEstimatedCost: number
* - status: string (pending, accepted, rejected, modified)
* - convertedToShoppingList: boolean
* - shoppingListId: string (ID of the list if it was converted)
*/

/**
* Collection: recipes
* Description: Stores suggested recipes based on inventory
*
* Fields:
* - id: string (automatically generated)
* - userId: string (reference to the user)
* - title: string (name of the recipe)
* - description: string
* - createdAt: timestamp
* - difficulty: string (easy, medium, hard)
* - prepTime: number (in minutes)
* - servings: number
* - ingredients: array of {
* name: string,
* quantity: number,
* unit: string,
* inStock: boolean
* }
* - instructions: array of strings
* - image: string (image URL, optional)
* - tags: array of strings
*/

/**
* Collection: priceComparisons
* Description: Stores price comparison results
*
* Fields:
* - id: string (automatically generated)
* - userId: string (reference to the user)
* - itemName: string (name of the product searched)
* - createdAt: timestamp
* - results: array of {
* storeName: string,
* price: number,
* unit: string,
* url: string (link to the product),
* lastUpdated: timestamp
* }
*/

/**
* Collection: userActions
* Description: Records user actions for personalization
*
* Fields:
* - id: string (automatically generated)
* - userId: string (user reference)
* - action: string (action type)
* - timestamp: timestamp
* - details: map (specific action details)
*/

// Export functions to create documents with the correct structure

/**
 * Create a user object with default values
 * @param {object} userData - user data got from the register form
 * @returns {object} user object to a firebase database
 */

export const createUserObject = (userData) => {
    return {
        uid: userData.uid,
        email: userData.email,
        displayName: userData.displayName || '',
        phoneNumber: userData.phoneNumber || '',
        address: {
            street: userData.street || '',
            city: userData.city || '',
            postcode: userData.postcode || '',
            country: userData.country || 'UK'
        },
        photoURL: userData.photoURL || '',
        createdAt: new Date(),
        updatedAt: new Date(),
        lastLogin: new Date(),
        role: 'user',
        isActive: true,
        settings: {
            notifications: true,
            theme: 'light',
            language: 'en'
        }
    };
};

/**
 * Create a object of Shopping List
 * @param {string} userId - user id
 * @param {string} name - name of the shopping List
 * @param {boolean} isAIGenerated - if the list is generated by Ai
 * @param {number} budget - budget of the list(optional)
 * @returns {object} shopping list object to a firebase database
 */

export const createShoppingListObject = (userId, name, isAIGenerated = false, budget = null) => {
    return {
        userId,
        name,
        createdAt: new Date(),
        updatedAt: new Date(),
        isActive: true,
        isAIGenerated,
        totalBudget: budget,
        items: []
    };
};

/**
 * Create a object of Shopping List Item
 * @param {string} name - name of the item
 * @param {number} quantity - quantity of the item
 * @param {string} unit - unit of the item
 * @param {number} estimatedPrice - price of the item estimated by the AI(optional)
 * @param {string} category - category of the item
 * @returns {object} shopping list item object to a firebase database
 */

export const createShoppingItemObject = (name, quantity, unit, estimatedPrice = null, category = '') => {
    return {
        id: uuidv4(),
        name,
        quantity,
        unit,
        estimatedPrice,
        checked: false,
        addedToStock: false,
        category,
        notes: ''
    };
};


/**
 * Create a object of Stock Item
 * @param {string} userId - user id
 * @param {string} name - name of the item
 * @param {number} quantity - quantity of the item
 * @param {string} unit - unit of the item
 * @param {number} minQuantity - minimum quantity of the item
 * @param {Object} Firestore Object formatted
 */

export const createStockItemObject = (userId, name, quantity, unit, minQuantity) => {
    return {
        userId,
        name,
        category: '',
        quantity,
        unit,
        minQuantity: minQuantity || Math.max(1, Math.floor(quantity * 0.2)),
        createdAt: new Date(),
        updatedAt: new Date(),
        lastPurchaseDate: new Date(),
        lastPurchasePrice: null,
        expiryDate: null,
        image: '',
        barcode: '',
        notes: '',
    };
};

/**
 * create a object of AI Suggestion
 * @param {string} userId - user id
 * @param {number} budget - budget of the list
 * @param {Array} items - array of items
 * @param {number} totalEstimatedCost - total cost of the list
 * @returns {object} AI suggestion object to a firebase database
 */
export const createAISuggestionObject = (userId, budget, items, totalEstimatedCost) => {
    return {
        userId,
        createdAt: new Date(),
        budget,
        items,
        totalEstimatedCost,
        status: 'pending',
        convertedToShoppingList: false,
        shoppingListId: null
    };
};

/**
 * create a object of Recipe
 * @param {string} userId - user id
 * @param {string} title - title of the recipe
 * @param {string} description - description of the recipe
 * @param {string} difficulty - difficulty level of the recipe
 * @param {number} prepTime - preparation time in minutes
 * @param {number} servings - number of servings
 * @param {Array} ingredients - array of ingredients
 * @param {Array} instructions - array of instructions
 * @param {Array} tags - array of tags
 * @returns {object} recipe object to a firebase database
 */
export const createRecipeObject = (userId, title, description, difficulty, prepTime, servings, ingredients, instructions, tags ) => {
    return {
        userId,
        title,
        description,
        createdAt: new Date(),
        difficulty,
        prepTime,
        servings,
        ingredients,
        instructions,
        image: '',
        tags: tags || []
    };
};

/**
 * create a object of Price Comparison
 * @param {string} userId - user id
 * @param {string} itemName - name of the product
 * @param {Array} results - array of price comparison results
 * @returns {object} price comparison object to a firebase database
 */
export const createPriceComparisonObject = (userId, itemName, results) => {
    return {
        userId,
        itemName: itemName.toLowerCase().trim(),
        createdAt: new Date(),
        results
    };
};

/**
 * create a object of User Action
 * @param {string} userId - user id
 * @param {string} action - action type
 * @param {Object} details - specific action details
 * @returns {object} user action object to a firebase database 
 */
export const createUserActionObject = (userId, action, details = {}) => {
    return {
        userId,
        action,
        timestamp: new Date(),
        details
    };
}; 